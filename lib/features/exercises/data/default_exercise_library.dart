  /// Every bundled exercise, ordered by category then name.
  static List<Exercise> get all => List<Exercise>.unmodifiable([
    ...chest,
    ...back,
    ...shoulders,
    ...biceps,
    ...triceps,
    ...legs,
    ...cardio,
    ...abs,
  ]);

  /// Exercises in [category], sorted alphabetically.
  static List<Exercise> of(ExerciseLibraryCategory category) {
    final exercises = switch (category) {
      ExerciseLibraryCategory.chest => chest,
      ExerciseLibraryCategory.back => back,
      ExerciseLibraryCategory.shoulders => shoulders,
      ExerciseLibraryCategory.biceps => biceps,
      ExerciseLibraryCategory.triceps => triceps,
      ExerciseLibraryCategory.legs => legs,
      ExerciseLibraryCategory.cardio => cardio,
      ExerciseLibraryCategory.abs => abs,
    };
    return List<Exercise>.of(exercises)
      ..sort((a, b) => a.name.toLowerCase().compareTo(b.name.toLowerCase()));
  }

  static Map<ExerciseLibraryCategory, List<Exercise>> get byCategory => {
    for (final category in ExerciseLibraryCategory.values)
      category: of(category),
  };

