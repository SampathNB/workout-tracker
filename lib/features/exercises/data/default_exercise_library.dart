/// Bundled workout library shipped with GymTrack.
///
/// Eight browse categories (Chest → Abs), each with 8–12 exercises and a
/// hypertrophy-oriented set/rep (or duration) prescription. Stable `default_*`
/// ids let [ExerciseLibrarySeeder] upsert missing entries on upgrade without
