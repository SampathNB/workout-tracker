  static Exercise _cardio({
    required String id,
    required String name,
    required Equipment equipment,
    required ExerciseTracking tracking,
    required int sets,
    int? repsMin,
    int? repsMax,
    int? durationMin,
    int? durationMax,
    int rest = 0,
    String? instructions,
  }) {
    final isReps = tracking == ExerciseTracking.repsOnly;
    return Exercise(
      id: id,
      name: name,
      primaryMuscle: MuscleGroup.cardio,
      libraryCategory: ExerciseLibraryCategory.cardio,
      equipment: equipment,
      category: ExerciseCategory.cardio,
      tracking: tracking,
      recommendedSets: sets,
      recommendedRepsMin: isReps ? (repsMin ?? 10) : 0,
      recommendedRepsMax: isReps ? (repsMax ?? repsMin ?? 10) : 0,
      recommendedDurationSeconds: isReps ? null : durationMin,
      recommendedDurationMaxSeconds: isReps ? null : (durationMax ?? durationMin),
      defaultRestSeconds: rest,
      instructions: instructions,
      isCustom: false,
      createdAt: _seededAt,
    );
  }
