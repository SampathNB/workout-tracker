    required String id,
    required String name,
    required ExerciseLibraryCategory library,
    required MuscleGroup primary,
    required int sets,
    required int repsMin,
    List<MuscleGroup> secondary = const [],
    Equipment equipment = Equipment.bodyweight,
    ExerciseCategory category = ExerciseCategory.hypertrophy,
    ExerciseTracking tracking = ExerciseTracking.weightAndReps,
    int? repsMax,
    int rest = 90,
    String? instructions,
  }) {
    return Exercise(
      id: id,
      name: name,
      primaryMuscle: primary,
      libraryCategory: library,
      secondaryMuscles: secondary,
      equipment: equipment,
      category: category,
      tracking: tracking,
      recommendedSets: sets,
      recommendedRepsMin: repsMin,
      recommendedRepsMax: repsMax ?? repsMin,
      defaultRestSeconds: rest,
      instructions: instructions,
      isCustom: false,
      createdAt: _seededAt,
    );
  }

